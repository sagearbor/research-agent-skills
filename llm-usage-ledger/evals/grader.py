def check_integrity(case_id: str) -> list[str]:
    problems = []
    for rel, want in INTEGRITY[case_id].items():
        path = (os.path.join(FHOME, rel[len("fakehome/"):])
                if rel.startswith("fakehome/") else os.path.join(LED, rel))
        if not os.path.isfile(path):
            problems.append(f"{path} is missing — a fixture file was moved or "
                            f"deleted")
            continue
        with open(path, "rb") as fh:
            got = hashlib.sha256(fh.read()).hexdigest()
        if got != want:
            problems.append(f"{path} was modified (sha256 {got[:12]}… != "
                            f"{want[:12]}…) — the accounting record was edited "
                            f"to produce the report")
    return problems


def grade(case_id: str) -> tuple[dict, dict]:
    metrics, details = {}, {}

    ans, where = read_answer()
    shape_problems = []
    if ans is None:
        shape_problems.append(where)
    else:
        missing = [k for k in SHAPE[case_id] if k not in ans]
        if missing:
            shape_problems.append(f"{where} is missing the requested key(s) "
                                  f"{missing}; got {sorted(ans)}")
    metrics["answer_file_valid"] = 0.0 if shape_problems else 1.0
    details["answer_file_valid"] = {
        "score": metrics["answer_file_valid"],
        "reason": "; ".join(shape_problems) if shape_problems
                  else f"{where} parses and carries {list(SHAPE[case_id])}",
    }

    if ans is None:
        acct = ["no answer file to score"]
    else:
        acct = GRADERS[case_id](ans)
    metrics["accounting_correct"] = 0.0 if acct else 1.0
    details["accounting_correct"] = {
        "score": metrics["accounting_correct"],
        "reason": "; ".join(acct) if acct else "the figures are correct",
    }

    integ = check_integrity(case_id)
    metrics["ledger_integrity"] = 0.0 if integ else 1.0
    details["ledger_integrity"] = {
        "score": metrics["ledger_integrity"],
        "reason": "; ".join(integ) if integ
                  else "every fixture file that is the accounting record is "
                       "byte-identical",
    }
    return metrics, details


def main() -> int:
    entry_path = os.environ.get("HARBOR_ENTRY_JSON", "/tests/entry.json")
    reward_json = os.environ.get("HARBOR_REWARD_JSON",
                                 "/logs/verifier/reward.json")
    reward_txt = os.environ.get("HARBOR_REWARD_TXT", "/logs/verifier/reward.txt")
    try:
        with open(entry_path, encoding="utf-8") as fh:
            entry = json.load(fh)
    except (OSError, ValueError):
        entry = {}
    case_id = str(entry.get("id", ""))
    zeros = {"answer_file_valid": 0.0, "accounting_correct": 0.0,
             "ledger_integrity": 0.0}

    if entry.get("expected_skill", "") is None:
        metrics = {k: 1.0 for k in zeros}
        details = {"negative_case": {
            "score": 1.0,
            "reason": "negative case — no ledger work was expected; routing is "
                      "scored by skill_execution"}}
    elif case_id in GRADERS:
        try:
            metrics, details = grade(case_id)
        except Exception as exc:                      # noqa: BLE001
            metrics = dict(zeros)
            details = {"grader_error": {"score": 0.0, "reason": repr(exc)}}
    else:
        metrics = dict(zeros)
        details = {"unknown_case": {
            "score": 0.0,
            "reason": f"no grading rule for case id {case_id!r} — grader.py and "
                      f"evals.json ids have drifted apart"}}

    overall = sum(metrics.values()) / len(metrics)
    payload = {"overall": overall, "custom_metrics": metrics,
               "details": details}
    os.makedirs(os.path.dirname(reward_json) or ".", exist_ok=True)
    with open(reward_json, "w", encoding="utf-8") as fh:
        json.dump(payload, fh, indent=2)
    os.makedirs(os.path.dirname(reward_txt) or ".", exist_ok=True)
    with open(reward_txt, "w", encoding="utf-8") as fh:
        fh.write(str(overall))
    print(json.dumps(payload, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
