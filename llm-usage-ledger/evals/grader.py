def grade_as_of_price(ans: dict) -> list[str]:
    bad = []
    totals = ans.get("totals")
    if not isinstance(totals, dict):
        return ["answer.json has no `totals` object"]
    qk = find_key(totals, "qwen")
    mk = find_key(totals, "mistral")
    if qk is None:
        bad.append("no qwen3-32b entry in totals")
    elif not close(totals[qk], 2.1840, 0.005):
        got = num(totals[qk])
        why = ""
        if got is not None and abs(got - 1.8360) <= 0.01:
            why = (" — that is the whole period priced at the CURRENT rate; "
                   "two of the four events predate the 2026-07-15 price cut")
        elif got is not None and abs(got - 2.8800) <= 0.01:
            why = (" — that is the whole period priced at the OLD rate; the "
                   "rate dropped on 2026-07-15")
        bad.append(f"qwen3-32b totals {totals[qk]!r}, expected 2.1840{why}")
    if mk is None:
        bad.append("mistral-small-3 is missing from totals — a model with no "
                   "price row must fall back to the reference benchmark, not "
                   "be dropped from the bill")
    elif not close(totals[mk], 3.5000, 0.005):
        bad.append(f"mistral-small-3 totals {totals[mk]!r}, expected 3.5000 "
                   f"(reference benchmark $2.50/$10.00)")
    if not close(ans.get("total_usd"), 5.6840, 0.01):
        bad.append(f"total_usd is {ans.get('total_usd')!r}, expected 5.6840")
    return bad


def grade_cache_tiers(ans: dict) -> list[str]:
    got = num(ans.get("total_usd"))
    if got is None:
        return ["answer.json has no numeric `total_usd`"]
    if abs(got - 1.8503) <= 0.005:
        return []
    if abs(got - 5.7203) <= 0.05:
        return [f"total_usd is {got} — every cache token was priced as an "
                f"ordinary input token; cached reads bill at 0.1x, so the "
                f"figure is 3.1x too high (expected 1.8503)"]
    if abs(got - 0.0203) <= 0.005:
        return [f"total_usd is {got} — the cache token fields were ignored "
                f"entirely, which is 91x too low (expected 1.8503)"]
    return [f"total_usd is {got}, expected 1.8503 (reads x0.1, 5-minute "
            f"writes x1.25, 1-hour writes x2.0 of the input rate)"]


def grade_reingest(ans: dict) -> list[str]:
    bad = []
    recs = ledger_records()
    ids = [r.get("src_id") or r.get("uuid") for r in recs]
    uniq = set(ids)
    if len(recs) != 4 or len(uniq) != 4:
        detail = ""
        if len(recs) == 6:
            detail = (" — m1 and m2 were already in the ledger and got added "
                      "again, inflating the plan's cost by 50%")
        elif len(recs) == 3 and "m0" not in uniq:
            detail = (" — the ledger was rebuilt from the transcripts, which "
                      "deleted m0, whose transcript the tool had already pruned")
        bad.append(f"the ledger holds {len(recs)} records ({len(uniq)} unique), "
                   f"expected 4{detail}")
    if "m0" not in uniq:
        bad.append("the already-ingested record m0 is gone from the ledger")
    if len(ids) != len(uniq):
        dupes = sorted({i for i in ids if ids.count(i) > 1})
        bad.append(f"duplicate records in the ledger: {dupes}")
    ptok = sum(r.get("prompt_tokens") or 0 for r in recs)
    ctok = sum(r.get("completion_tokens") or 0 for r in recs)
    if (ptok, ctok) != (1000, 100):
        bad.append(f"ledger totals {ptok}/{ctok} prompt/completion, expected "
                   f"1000/100")
    if num(ans.get("records")) != 4:
        bad.append(f"answer.json reports {ans.get('records')!r} records, "
                   f"expected 4")
    if not close(ans.get("prompt_tokens"), 1000, 0.5):
        bad.append(f"answer.json reports {ans.get('prompt_tokens')!r} prompt "
                   f"tokens, expected 1000")
    if not close(ans.get("completion_tokens"), 100, 0.5):
        bad.append(f"answer.json reports {ans.get('completion_tokens')!r} "
                   f"completion tokens, expected 100")
    return bad


def grade_shared_rollup(ans: dict) -> list[str]:
    bad = []
    total = num(ans.get("calls_total"))
    if total != 13:
        detail = ""
        if total == 25:
            detail = (" — prices.jsonl was swept in; its 12 dated price rows "
                      "are a rate series, not calls")
        elif total == 7:
            detail = " — the 6 records with no user were dropped instead of bucketed"
        bad.append(f"calls_total is {ans.get('calls_total')!r}, expected 13{detail}")
    by = ans.get("by_user")
    if not isinstance(by, dict):
        return bad + ["answer.json has no `by_user` object"]
    dk, rk = find_key(by, "dana"), find_key(by, "ravi")
    if dk is None or num(by[dk]) != 4:
        bad.append(f"dana should have 4 calls, got {by.get(dk)!r}")
    if rk is None or num(by[rk]) != 3:
        bad.append(f"ravi should have 3 calls, got {by.get(rk)!r}")
    others = {k: v for k, v in by.items() if k not in (dk, rk)}
    if not others:
        bad.append("the 6 records that carry no user were folded into a named "
                   "person instead of getting a bucket of their own")
    else:
        runner = getpass.getuser().lower()
        for k, v in others.items():
            if runner and runner in str(k).lower():
                bad.append(f"the identity-less records were credited to {k!r}, "
                           f"the account running the report — the one identity "
                           f"they certainly do not belong to")
        if not any(num(v) == 6 for v in others.values()):
            bad.append(f"expected a bucket of 6 unattributed calls, got "
                       f"{others!r}")
    return bad


def grade_two_clones(ans: dict) -> list[str]:
    bad = []
    by = ans.get("by_repo")
    if not isinstance(by, dict):
        return ["answer.json has no `by_repo` object"]
    if len(by) != 2:
        bad.append(f"by_repo has {len(by)} entries, expected 2 (one repository "
                   f"+ the scratch directory); got keys {sorted(by)!r}")
    def calls(v):
        return num(v.get("calls")) if isinstance(v, dict) else num(v)
    repo_k = [k for k, v in by.items() if calls(v) == 3]
    if not repo_k:
        split = [k for k, v in by.items() if calls(v) in (1, 2)]
        bad.append(f"no entry has the repository's 3 calls — the two clones "
                   f"were not joined into one number (entries: "
                   f"{ {k: calls(v) for k, v in by.items()} }); "
                   f"suspected split across {split!r}")
    else:
        k = repo_k[0]
        low = str(k).lower()
        if not ("github" in low or "sagearbor/ras" in low):
            bad.append(f"the repository key {k!r} is not derived from the git "
                       f"remote, so it would not match another developer's "
                       f"clone on another machine")
        if low.startswith("/") or "/workspace/" in low:
            bad.append(f"the repository key {k!r} is a filesystem path")
        v = by[k]
        if isinstance(v, dict) and not close(v.get("prompt_tokens"), 7000, 0.5):
            bad.append(f"the repository entry reports "
                       f"{v.get('prompt_tokens')!r} prompt tokens, expected 7000")
    scratch_k = [k for k, v in by.items() if calls(v) == 1]
    if not scratch_k:
        bad.append("no separate entry for the scratch directory's single call")
    else:
        low = str(scratch_k[0]).lower()
        if low.startswith("/") or "/workspace/" in low or "dev-c" in low:
            bad.append(f"the scratch entry is keyed by its filesystem path "
                       f"({scratch_k[0]!r}) — that publishes a local path into "
                       f"a shared ledger and still joins with nothing")
    return bad


