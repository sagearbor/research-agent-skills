# ----------------------------------------------------------------- helpers
def read_answer() -> tuple[dict | None, str]:
    path = os.path.join(OUT, "answer.json")
    if not os.path.isfile(path):
        hits = sorted(glob.glob(os.path.join(OUT, "**/*.json"), recursive=True))
        if not hits:
            return None, f"no answer.json (and no .json at all) under {OUT}"
        path = hits[0]
    try:
        with open(path, encoding="utf-8") as fh:
            data = json.load(fh)
    except (OSError, ValueError) as exc:
        return None, f"{path} is not readable JSON ({exc})"
    if not isinstance(data, dict):
        return None, f"{path} is a {type(data).__name__}, expected an object"
    return data, path


def num(x):
    """Accept 1.85, '1.85' and '$1.85' — the value is the answer, not its
    typography. Returns None for anything that is not a number."""
    if isinstance(x, bool):
        return None
    if isinstance(x, (int, float)):
        return float(x)
    if isinstance(x, str):
        m = re.search(r"-?\d+(?:\.\d+)?", x.replace(",", ""))
        if m:
            return float(m.group(0))
    return None


def close(got, want, tol=USD_TOL):
    g = num(got)
    return g is not None and abs(g - want) <= tol


def ledger_records() -> list[dict]:
    """Every Claude Code record the ledger holds, however many files it is
    spread over — an importer that wrote a second file beside the existing one
    has still double-counted."""
    recs = []
    for path in sorted(glob.glob(os.path.join(LED, "claude-code-*.jsonl"))):
        with open(path, encoding="utf-8", errors="replace") as fh:
            for line in fh:
                if line.strip():
                    try:
                        recs.append(json.loads(line))
                    except ValueError:
                        pass
    return recs


def find_key(d: dict, *needles: str) -> str | None:
    """First key containing any needle, case-insensitively. Used so a model or
    person can be reported as 'qwen3-32b', 'Qwen3-32B' or 'qwen3-32b (local)'
    without the grader pretending that is a different answer."""
    for k in d:
        low = str(k).lower()
        if any(n in low for n in needles):
            return k
    return None


