#!/usr/bin/env python3
"""Deterministic BYOG grader for the llm-usage-ledger Tier-3 eval set.

Every claim this skill makes is a claim about a NUMBER: what the month cost
once each event is priced at the rate in force on its own date, what a flat-fee
plan absorbed once cache reads are booked at a tenth of the input rate, how
many records a ledger holds after an import that must be safe to repeat. An
LLM judge reading a trajectory cannot tell $1.8503 from $5.7203 with any
confidence, and those two answers differ by a factor of three. So the numbers
live here and the behaviour lives in `assertions`.

Contract (docs/custom-graders.mdx):
  read   $HARBOR_ENTRY_JSON   (default /tests/entry.json)
  write  $HARBOR_REWARD_JSON  (default /logs/verifier/reward.json)
  write  $HARBOR_REWARD_TXT   (default /logs/verifier/reward.txt)

grading.mode is default_plus_custom, so scores go under "custom_metrics" and
the six reserved names (security, skill_execution, skill_efficiency, accuracy,
goal_accuracy, behavior_check) are never written.

Metrics, the same three for every positive case:
  answer_file_valid   /workspace/output/answer.json exists, parses, and has
                      the shape the prompt asked for
  accounting_correct  the figure is right, and the reason string names which
                      specific wrong answer was produced when it is not
  ledger_integrity    the fixture files that are the accounting record are
                      byte-identical afterwards. A reporting tool that edits
                      the books to make the report come out has not reported.
"""
